// Writes docs/assets/font-fit.css: a width-normalised twin of every bundled theme typeface, so the
// site doesn't reflow when a theme swaps faces. Each twin is the same file with `size-adjust` set so
// a sample paragraph is as wide as the Osmium reference face (display: Chakra Petch @600, body: IBM
// Plex Sans @400, mono: JetBrains Mono @400). site-theme.js puts the twin first in the font stack.
// Run by sync-site.js. The ratios were measured in-browser (canvas measureText of one fixed sample
// string, reference width / face width); re-measure if a theme's faces change.
'use strict';
const fs = require('fs');
const path = require('path');

const { RATIOS, METRICS } = require('./font-fit-data');

// Ascent / descent (% of the font size) of the reference faces; every twin is forced to them so a
// `line-height: normal` line is the same height in every theme. Divided by the ratio because the
// overrides are scaled by size-adjust.
const BIAS = Number(process.env.FIT_BIAS || 1); // < 1 sizes every non-reference face a hair small so paragraphs rarely gain a line

const fontsCss =fs.readFileSync(path.join(__dirname, '..', 'docs', 'demo', 'fonts', 'fonts.css'), 'utf8');
const faces = [...fontsCss.matchAll(/@font-face\{[^}]*\}/g)].map((m) => m[0]);
let out = '/* GENERATED by scripts/site-font-fit.js; do not edit. */\n';
for (const [role, table] of Object.entries(RATIOS)){
  for (const [fam, ratio] of Object.entries(table)){
    // Cap the enlargement: scaling a condensed face up to a normal width makes its letters towering
    // (Big Shoulders at x1.46 collided its own two title lines). Narrower text is harmless.
    const eff = Math.min(ratio, 1.2) * (ratio === 1 ? 1 : BIAS);
    for (const f of faces){
      if (!f.includes(`font-family:'${fam}'`)) continue;
      out += f.replace(`font-family:'${fam}'`, `font-family:'${fam} Fit ${role}'`)
        .replace("url('", "url('../demo/fonts/")
        .replace(/\}$/, ` size-adjust:${(eff * 100).toFixed(2)}%; ascent-override:${(METRICS[role][0] / eff).toFixed(2)}%;` +
          ` descent-override:${(METRICS[role][1] / eff).toFixed(2)}%; line-gap-override:0%; }`) + '\n';
    }
  }
}
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'assets', 'font-fit.css'), out);
