// Writes renderer/fonts/font-fit.css: a metrics-normalised override of every
// bundled theme face, loaded right after fonts.css (index.html). It re-declares
// each family with the SAME name plus `size-adjust` / `ascent-override` /
// `descent-override`, so a face swap changes the lettering but never the text's
// width or line height — which is what keeps every theme's controls the same
// size. (The site does the same thing with per-role twin names in
// docs/assets/font-fit.css; this is the app-side equivalent.)
//
// Role per family is derived: a family used in the mono or body ratio tables
// keeps that role (body wins over display when a family is listed in both,
// since all UI text is body), otherwise it's a display face. A new bundled
// face needs a RATIOS entry in scripts/font-fit-data.js or this script throws.
// Run by `npm run build:renderer`. Don't hand-edit font-fit.css.
'use strict';
const fs = require('fs');
const path = require('path');
const { RATIOS, METRICS } = require('./font-fit-data');

// Eczar (Blood Moon's head/tab face) is app-only — the site maps display/body/
// mono and never renders it — so it has no site measurement. Width ratio
// measured from the bundled woff2 against Chakra Petch @600 (same method).
const EXTRA_DISPLAY = { 'Eczar': 1.07 };
const DISPLAY = Object.assign({}, RATIOS.display, EXTRA_DISPLAY);

const BIAS = 1;
function role(fam){
  if (fam in RATIOS.mono) return 'mono';
  if (fam in RATIOS.body) return 'body';
  if (fam in DISPLAY) return 'display';
  return null;
}
function ratio(fam, r){
  return r === 'display' ? DISPLAY[fam] : r === 'mono' ? RATIOS.mono[fam] : RATIOS.body[fam];
}

const fontsCss = fs.readFileSync(path.join(__dirname, '..', 'renderer', 'fonts', 'fonts.css'), 'utf8');
const faces = [...fontsCss.matchAll(/@font-face\{[^}]*\}/g)].map((m) => m[0]);
let out = '/* GENERATED by scripts/app-font-fit.js; do not edit. */\n';
for (const f of faces){
  const m = f.match(/font-family:'([^']+)'/);
  if (!m) throw new Error('app-font-fit: face with no font-family: ' + f);
  const fam = m[1], r = role(fam);
  if (!r) throw new Error(`app-font-fit: no RATIOS entry for '${fam}' — add it to scripts/font-fit-data.js`);
  const eff = Math.min(ratio(fam, r), 1.2) * (ratio(fam, r) === 1 ? 1 : BIAS);
  out += f.replace(/\}$/, ` size-adjust:${(eff * 100).toFixed(2)}%; ascent-override:${(METRICS[r][0] / eff).toFixed(2)}%;` +
    ` descent-override:${(METRICS[r][1] / eff).toFixed(2)}%; line-gap-override:0%; }`) + '\n';
}
fs.writeFileSync(path.join(__dirname, '..', 'renderer', 'fonts', 'font-fit.css'), out);
