#!/usr/bin/env node
// Compiles the committed Danbooru tag-group snapshot (scripts/tag-categories/raw/*.json)
// plus the hand-authored fallback rules (scripts/tag-categories/rules/*.json) into the
// generated renderer module src/renderer/tag-categories-data.ts.
//
// The app never hits the network: this is a build-time step run by hand when the snapshot
// changes. Regenerate with `npm run build:tag-categories` (or `node
// scripts/build-tag-categories.js`).
//
// Why a snapshot instead of live fetching: Danbooru is behind bot protection — direct
// Node/PowerShell HTTP gets a 403, so the group pages are fetched once (via a browser-like
// agent) and committed under scripts/tag-categories/raw/. See notes/Features/Tag-Sorting.md.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(__dirname, 'tag-categories');
const OUT = path.join(ROOT, 'src', 'renderer', 'tag-categories-data.ts');

// Most-specific-content first: a tag present in several categories' group lists resolves
// to the first one here. 'other' is the implicit fallback and is never seeded.
//
// Limbs sits ABOVE pose deliberately (revising the feature's initial "Pose before Limbs"
// order): Danbooru's Posture page cross-references the Gestures page, so posture's group
// list contains gesture tags too ("waving", "salute", "akanbe", ...) — with Pose first
// those all silently became Pose. Hands/gestures are the more specific fact, so they win.
const ORDER = ['sexual', 'limbs', 'pose', 'clothes', 'body', 'character', 'scene', 'effects'];

// Obvious non-content tags the (deliberately liberal) snapshot extraction swept in from
// group pages' prose; dropping them here sends them to 'other' instead of a wrong bucket.
const DENY = new Set([
  'highres', 'absurdres', 'lowres', 'hires', 'huge filesize',
  'comic', '4koma', '1koma', '2koma', '3koma',
  'commentary', 'commentary request', 'translated', 'translation request', 'check translation',
  'bad id', 'bad link', 'third-party edit', 'watermark', 'english text', 'artist name'
]);

const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));

const seeds = new Map();
const perCat = {};
for (const cat of ORDER) {
  const file = path.join(SRC, 'raw', cat + '.json');
  if (!fs.existsSync(file)) { console.warn('[warn] missing raw snapshot:', cat); continue; }
  const tags = readJson(file);
  perCat[cat] = tags.length;
  for (const raw of tags) {
    const key = String(raw).toLowerCase().trim();
    if (!key || seeds.has(key) || DENY.has(key)) continue; // first category in ORDER wins an overlap
    seeds.set(key, cat);
  }
}

const rules = [];
for (const cat of ORDER) {
  const file = path.join(SRC, 'rules', cat + '.json');
  if (!fs.existsSync(file)) continue;
  const kws = readJson(file).map((k) => String(k).toLowerCase().trim()).filter(Boolean);
  if (kws.length) rules.push({ id: cat, keywords: Array.from(new Set(kws)) });
}

const seedEntries = Array.from(seeds.entries()).sort((a, b) => a[0].localeCompare(b[0]));

const lines = [];
lines.push('// GENERATED by scripts/build-tag-categories.js — DO NOT EDIT BY HAND.');
lines.push('// Sources: scripts/tag-categories/raw/*.json (Danbooru tag-group snapshot) and');
lines.push('//          scripts/tag-categories/rules/*.json (hand-authored fallback keywords).');
lines.push('// Regenerate: `npm run build:tag-categories`.');
lines.push('');
lines.push("export type TagCategoryId = 'character' | 'body' | 'clothes' | 'limbs' | 'sexual' | 'pose' | 'scene' | 'effects' | 'other';");
lines.push('');
lines.push('/** Display order in Single mode and the card modal. */');
lines.push("export const TAG_CATEGORY_ORDER: TagCategoryId[] = ['character', 'body', 'clothes', 'limbs', 'sexual', 'pose', 'scene', 'effects', 'other'];");
lines.push('');
lines.push('/** Exact tag -> category, compiled from Danbooru tag groups (most-specific category wins overlaps). */');
lines.push('export const TAG_CATEGORY_SEEDS: Record<string, TagCategoryId> = {');
for (const [key, cat] of seedEntries) lines.push('  ' + JSON.stringify(key) + ': ' + JSON.stringify(cat) + ',');
lines.push('};');
lines.push('');
lines.push('/** Fallback keyword rules (word-boundary matched) for tags absent from the seed map, in precedence order. */');
lines.push('export const TAG_CATEGORY_RULES: { id: TagCategoryId; keywords: string[] }[] = [');
for (const r of rules) lines.push('  { id: ' + JSON.stringify(r.id) + ', keywords: ' + JSON.stringify(r.keywords) + ' },');
lines.push('];');
lines.push('');
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log('[tag-categories] raw per category:', JSON.stringify(perCat));
console.log('[tag-categories] unique seeded tags:', seedEntries.length);
console.log('[tag-categories] rules:', rules.map((r) => `${r.id}:${r.keywords.length}`).join(', '));
console.log('[tag-categories] wrote', path.relative(ROOT, OUT));
